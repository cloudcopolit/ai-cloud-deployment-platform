from __future__ import annotations

import json
import re

from openai import OpenAI

from app.config import settings
from app.schemas import ArchitectureAnalysis, DeveloperIntent, RoutingInfo
from app.services.evaluator import evaluate_analysis
from app.services.mermaid import architecture_to_mermaid
from app.services.prompt_builder import build_analysis_prompt
from app.services.router import choose_initial_model


SYSTEM_PROMPT = """You are a senior software architect analyzing an uploaded codebase.

Use repository evidence first.

Your job:
1. Infer the CURRENT architecture from repository evidence.
2. Distinguish facts, inference, and assumptions.
3. Identify important components and their relationships.
4. Give concise and practical recommendations.
5. Never invent components merely because they would be good design choices.
6. Put uncertain claims in assumptions.
7. Component IDs must be unique.
8. Connections must reference valid component IDs.
9. Return JSON only.
10. Do not generate Mermaid; the server generates it deterministically.
"""


def _strip_code_fence(text: str) -> str:
    text = text.strip()

    if text.startswith("```"):
        text = re.sub(
            r"^```(?:json)?\s*",
            "",
            text,
            flags=re.I,
        )
        text = re.sub(
            r"\s*```$",
            "",
            text,
        )

    return text.strip()


def _analysis_schema() -> dict:
    schema = ArchitectureAnalysis.model_json_schema()

    # Generated by the server, not by the LLM.
    for key in ("mermaid", "routing", "intent"):
        schema["properties"].pop(key, None)

        if "required" in schema and key in schema["required"]:
            schema["required"].remove(key)

    return schema


def _client() -> OpenAI:
    if not settings.openrouter_api_key:
        raise RuntimeError(
            "OPENROUTER_API_KEY is missing. Add it to .env."
        )

    return OpenAI(
        api_key=settings.openrouter_api_key,
        base_url="https://openrouter.ai/api/v1",
    )


def _run_model(
    model: str,
    repo_text: str,
    intent: DeveloperIntent,
) -> ArchitectureAnalysis:

    prompt = build_analysis_prompt(
        intent,
        repo_text,
        json.dumps(
            _analysis_schema(),
            ensure_ascii=False,
        ),
    )

    response = _client().chat.completions.create(
        model=model,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": prompt,
            },
        ],
        temperature=0.1,
        max_tokens=settings.max_output_tokens,
        response_format={
            "type": "json_object",
        },
    )

    raw = response.choices[0].message.content or ""

    if not raw.strip():
        raise RuntimeError(
            f"Model '{model}' returned an empty response."
        )

    try:
        data = json.loads(
            _strip_code_fence(raw)
        )
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Model '{model}' returned invalid JSON."
        ) from exc

    try:
        return ArchitectureAnalysis.model_validate(data)
    except Exception as exc:
        raise ValueError(
            f"Model '{model}' returned JSON that does not match the required schema."
        ) from exc


def _classify_cheap_failure(exc: Exception) -> str:
    """
    Convert cheap-model failures into stable cascade reasons.
    """

    error_name = type(exc).__name__
    message = str(exc).lower()

    if "invalid json" in message:
        return "cheap_model_invalid_json"

    if "schema" in message:
        return "cheap_model_schema_validation_failure"

    if "empty response" in message:
        return "cheap_model_empty_response"

    if "ratelimit" in error_name.lower() or "429" in message:
        return "cheap_model_rate_limited"

    if "authentication" in error_name.lower() or "401" in message:
        return "cheap_model_authentication_failure"

    if (
        "apistatus" in error_name.lower()
        or "apierror" in error_name.lower()
        or "provider" in message
    ):
        return "cheap_model_provider_error"

    return f"cheap_model_failure:{error_name}"


def _finish_analysis(
    analysis: ArchitectureAnalysis,
    intent: DeveloperIntent,
) -> ArchitectureAnalysis:

    analysis.mermaid = architecture_to_mermaid(analysis)
    analysis.intent = intent

    return analysis


def analyze_repository(
    repo_text: str,
    intent: DeveloperIntent,
    routing_mode: str = "auto",
) -> ArchitectureAnalysis:

    mode = (
        routing_mode
        if routing_mode in {"auto", "cheap", "strong"}
        else "auto"
    )

    decision = choose_initial_model(
        repo_text,
        intent,
        mode,
    )

    # ---------------------------------------------------------
    # STRONG-ONLY BASELINE
    # ---------------------------------------------------------

    if mode == "strong":
        strong = _run_model(
            settings.strong_model,
            repo_text,
            intent,
        )

        strong = _finish_analysis(
            strong,
            intent,
        )

        strong.routing = RoutingInfo(
            mode="strong",

            initial_route="strong",
            initial_model=settings.strong_model,

            final_tier="strong",
            final_model=settings.strong_model,

            pre_route_score=decision.complexity_score,
            pre_route_threshold=decision.threshold,
            pre_route_reasons=decision.reasons,

            cheap_attempted=False,
            escalated=False,

            escalation_reasons=[],
            quality=None,
        )

        return strong

    # ---------------------------------------------------------
    # CHEAP-ONLY BASELINE
    # ---------------------------------------------------------

    if mode == "cheap":
        cheap = _run_model(
            settings.cheap_model,
            repo_text,
            intent,
        )

        quality = evaluate_analysis(
            cheap,
            intent,
        )

        cheap = _finish_analysis(
            cheap,
            intent,
        )

        cheap.routing = RoutingInfo(
            mode="cheap",

            initial_route="cheap",
            initial_model=settings.cheap_model,

            final_tier="cheap",
            final_model=settings.cheap_model,

            pre_route_score=decision.complexity_score,
            pre_route_threshold=decision.threshold,
            pre_route_reasons=decision.reasons,

            cheap_attempted=True,
            escalated=False,

            escalation_reasons=[],
            quality=quality,
        )

        return cheap

    # ---------------------------------------------------------
    # AUTO MODE:
    # obvious hard case -> strong directly
    # ---------------------------------------------------------

    if decision.tier == "strong":
        strong = _run_model(
            settings.strong_model,
            repo_text,
            intent,
        )

        strong = _finish_analysis(
            strong,
            intent,
        )

        strong.routing = RoutingInfo(
            mode="auto",

            initial_route="strong",
            initial_model=settings.strong_model,

            final_tier="strong",
            final_model=settings.strong_model,

            pre_route_score=decision.complexity_score,
            pre_route_threshold=decision.threshold,
            pre_route_reasons=decision.reasons,

            cheap_attempted=False,
            escalated=False,

            escalation_reasons=[],
            quality=None,
        )

        return strong

    # ---------------------------------------------------------
    # AUTO MODE:
    # cheap-first cascade
    # ---------------------------------------------------------

    escalation_reasons: list[str] = []
    quality = None

    try:
        cheap = _run_model(
            settings.cheap_model,
            repo_text,
            intent,
        )

        quality = evaluate_analysis(
            cheap,
            intent,
        )

        # Cheap result is good enough.
        if quality.score >= settings.quality_threshold:

            cheap = _finish_analysis(
                cheap,
                intent,
            )

            cheap.routing = RoutingInfo(
                mode="auto",

                initial_route="cheap",
                initial_model=settings.cheap_model,

                final_tier="cheap",
                final_model=settings.cheap_model,

                pre_route_score=decision.complexity_score,
                pre_route_threshold=decision.threshold,
                pre_route_reasons=decision.reasons,

                cheap_attempted=True,
                escalated=False,

                escalation_reasons=[],
                quality=quality,
            )

            return cheap

        # Cheap result was valid, but quality was insufficient.
        escalation_reasons.extend(
            quality.reasons
            or [
                (
                    f"cheap quality score {quality.score:.2f} "
                    f"was below threshold "
                    f"{settings.quality_threshold:.2f}"
                )
            ]
        )

    except Exception as exc:

        # Important:
        # cheap-model failure does NOT crash the request.
        # It becomes a cascade signal.
        reason = _classify_cheap_failure(exc)

        escalation_reasons.append(reason)

        print(
            "[CASCADE] Cheap model failed:",
            reason,
            "|",
            str(exc),
        )

    # ---------------------------------------------------------
    # CASCADE TO STRONG MODEL
    # ---------------------------------------------------------

    print(
        "[CASCADE] Escalating to:",
        settings.strong_model,
        "| reasons:",
        escalation_reasons,
    )

    strong = _run_model(
        settings.strong_model,
        repo_text,
        intent,
    )

    strong = _finish_analysis(
        strong,
        intent,
    )

    strong.routing = RoutingInfo(
        mode="auto",

        initial_route="cheap",
        initial_model=settings.cheap_model,

        final_tier="strong",
        final_model=settings.strong_model,

        pre_route_score=decision.complexity_score,
        pre_route_threshold=decision.threshold,
        pre_route_reasons=decision.reasons,

        cheap_attempted=True,
        escalated=True,

        escalation_reasons=escalation_reasons,
        quality=quality,
    )

    return strong
