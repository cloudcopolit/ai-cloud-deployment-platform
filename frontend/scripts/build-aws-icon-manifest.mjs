#!/usr/bin/env node
/*
 * Copies only the official AWS Architecture Icons the diagram uses, byte-for-byte, from the
 * git-ignored package in vendor/aws-icons/ into public/aws-icons/ (lowercase names, safe on
 * case-sensitive file systems) and writes src/lib/aws-icons/manifest.ts. See ADR-020.
 *
 *   node scripts/build-aws-icon-manifest.mjs [--package vendor/aws-icons]
 *
 * Component types without an official icon get no entry; the diagram draws a neutral box and
 * the type is listed in WORKLOG.md §8.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const arg = process.argv.indexOf('--package')
const pkg = resolve(root, arg > 0 ? process.argv[arg + 1] : 'vendor/aws-icons')
const RELEASE = '07312026'

const svc = (category, file) => `Architecture-Service-Icons_${RELEASE}/Arch_${category}/48/Arch_${file}_48.svg`
const res = (file) => `Resource-Icons_${RELEASE}/Res_General-Icons/Res_48_Light/Res_${file}_48_Light.svg`
const grp = (file) => `Architecture-Group-Icons_${RELEASE}/${file}_32.svg`

/** key → [official title, path inside the package]. Keys are ArchitecturePlan component types. */
const ICONS = {
  ecs_service: ['Amazon Elastic Container Service', svc('Containers', 'Amazon-Elastic-Container-Service')],
  fargate: ['AWS Fargate', svc('Containers', 'AWS-Fargate')],
  ecr: ['Amazon Elastic Container Registry', svc('Containers', 'Amazon-Elastic-Container-Registry')],
  lambda: ['AWS Lambda', svc('Compute', 'AWS-Lambda')],
  alb: ['Elastic Load Balancing', svc('Networking-Content-Delivery', 'Elastic-Load-Balancing')],
  vpc: ['Amazon Virtual Private Cloud', svc('Networking-Content-Delivery', 'Amazon-Virtual-Private-Cloud')],
  cloudfront: ['Amazon CloudFront', svc('Networking-Content-Delivery', 'Amazon-CloudFront')],
  route53: ['Amazon Route 53', svc('Networking-Content-Delivery', 'Amazon-Route-53')],
  api_gateway: ['Amazon API Gateway', svc('Networking-Content-Delivery', 'Amazon-API-Gateway')],
  rds: ['Amazon RDS', svc('Databases', 'Amazon-RDS')],
  elasticache: ['Amazon ElastiCache', svc('Databases', 'Amazon-ElastiCache')],
  dynamodb: ['Amazon DynamoDB', svc('Databases', 'Amazon-DynamoDB')],
  documentdb: ['Amazon DocumentDB', svc('Databases', 'Amazon-DocumentDB')],
  s3: ['Amazon Simple Storage Service', svc('Storage', 'Amazon-Simple-Storage-Service')],
  sqs: ['Amazon Simple Queue Service', svc('Application-Integration', 'Amazon-Simple-Queue-Service')],
  amazon_mq: ['Amazon MQ', svc('Application-Integration', 'Amazon-MQ')],
  msk: ['Amazon Managed Streaming for Apache Kafka', svc('Analytics', 'Amazon-Managed-Streaming-for-Apache-Kafka')],
  opensearch: ['Amazon OpenSearch Service', svc('Analytics', 'Amazon-OpenSearch-Service')],
  cloudwatch: ['Amazon CloudWatch', svc('Management-Tools', 'Amazon-CloudWatch')],
  secrets_manager: ['AWS Secrets Manager', svc('Security-Identity', 'AWS-Secrets-Manager')],
  acm: ['AWS Certificate Manager', svc('Security-Identity', 'AWS-Certificate-Manager')],
  waf: ['AWS WAF', svc('Security-Identity', 'AWS-WAF')],
  users: ['Users', res('Users')],
  internet: ['Internet', res('Internet')],
  group_aws_cloud: ['AWS Cloud', grp('AWS-Cloud-logo')],
  group_region: ['Region', grp('Region')],
  group_vpc: ['Virtual private cloud (VPC)', grp('Virtual-private-cloud-VPC')],
  group_public_subnet: ['Public subnet', grp('Public-subnet')],
  group_private_subnet: ['Private subnet', grp('Private-subnet')]
}

if (!existsSync(pkg)) {
  console.error(`AWS icon package not found at ${pkg}. Download release ${RELEASE} from`)
  console.error('https://aws.amazon.com/architecture/icons/ and unzip it there (see ADR-020).')
  process.exit(1)
}

const out = join(root, 'public', 'aws-icons')
const keep = new Set(['NOTICE.md'])
mkdirSync(out, { recursive: true })
for (const name of readdirSync(out)) if (!keep.has(name)) rmSync(join(out, name))

const lines = []
for (const [key, [title, rel]] of Object.entries(ICONS)) {
  const from = join(pkg, rel)
  if (!existsSync(from)) {
    console.error(`missing in package: ${rel}`)
    process.exit(1)
  }
  copyFileSync(from, join(out, `${key}.svg`)) // unmodified (AWS icon terms)
  lines.push(`  ${key}: { src: '/aws-icons/${key}.svg', title: ${JSON.stringify(title)}, source: ${JSON.stringify(rel)} }`)
}

const manifest = `// Generated by scripts/build-aws-icon-manifest.mjs from the official AWS Architecture Icons
// (release ${RELEASE}). Do not edit by hand; re-run the script.
export const AWS_ICON_RELEASE = '${RELEASE}'

export const AWS_ICONS = {
${lines.join(',\n')}
} as const

export type AwsIconKey = keyof typeof AWS_ICONS
`
mkdirSync(join(root, 'src', 'lib', 'aws-icons'), { recursive: true })
writeFileSync(join(root, 'src', 'lib', 'aws-icons', 'manifest.ts'), manifest)
console.log(`${Object.keys(ICONS).length} official icons copied to public/aws-icons/`)
